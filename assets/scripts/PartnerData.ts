export function getPartnerPortraitPath(partnerId: string): string {
    const galleryPartners = [
        'shen-xinglan',
        'jiang-yanbai',
        'jiang-yanbai-hoodie',
        'xia-yang',
        'lu-qinglan',
        'lu-qinglan-hoodie',
        'gu-chenzhou',
    ];
    if (galleryPartners.indexOf(partnerId) >= 0) {
        return `scene/gallery/${partnerId}/spriteFrame`;
    }
    const newLeadIndex: Record<string, number> = {
        'liang-xingye': 1,
        'tang-qi': 2,
        'xie-wujiu': 3,
        'pei-yuchuan': 4,
        'qi-guanlan': 5,
        'cheng-yanli': 6,
        'huo-wenzhou': 7,
        'song-zhao': 8,
        'wen-xuechuan': 9,
        'chu-yao': 10,
        'shen-yuheng': 11,
        'jing-mo': 12,
        'su-yan': 13,
        'ye-ci': 14,
        'cang-lan': 15,
        'pei-yao': 16,
        'xiao-tang': 17,
        'shen-qinghe': 18,
        'sha-luo': 19,
        'wen-yu': 20,
        'jiang-xubai': 21,
        'su-linyuan': 22,
        'ji-xingran': 23,
        'lu-shiyue': 24,
    };
    const index = newLeadIndex[partnerId];
    if (index) {
        const prefix = index < 10 ? `0${index}` : String(index);
        return `characters/new-male-leads/${prefix}-${partnerId}/spriteFrame`;
    }
    return 'scene/gallery/jiang-yanbai/spriteFrame';
}
